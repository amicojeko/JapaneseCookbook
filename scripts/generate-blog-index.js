// Generates src/data/blog-index.ts with the latest blog posts so the homepage
// (and any other docs page) can render a "Dal blog" strip without depending on
// runtime blog-plugin data. Mirrors the pattern of generate-ingredient-recipes.js.

const fs = require('fs');
const path = require('path');
const matter = require('gray-matter');
const yaml = require('js-yaml');

const BLOG_ROOT = path.join(process.cwd(), 'blog');
const AUTHORS_FILE = path.join(BLOG_ROOT, 'authors.yml');
const OUTPUT_FILE = path.join(process.cwd(), 'src', 'data', 'blog-index.ts');
const MAX_POSTS = 6;

function readAuthors() {
  if (!fs.existsSync(AUTHORS_FILE)) return {};
  const raw = fs.readFileSync(AUTHORS_FILE, 'utf8');
  return yaml.load(raw) || {};
}

function listPostFiles() {
  if (!fs.existsSync(BLOG_ROOT)) return [];
  const entries = fs.readdirSync(BLOG_ROOT, {withFileTypes: true});
  const files = [];
  for (const entry of entries) {
    if (entry.name.startsWith('_') || entry.name.startsWith('.')) continue;
    const full = path.join(BLOG_ROOT, entry.name);
    if (entry.isDirectory()) {
      const indexMd = path.join(full, 'index.md');
      const indexMdx = path.join(full, 'index.mdx');
      if (fs.existsSync(indexMd)) files.push(indexMd);
      else if (fs.existsSync(indexMdx)) files.push(indexMdx);
    } else if (
      (entry.name.endsWith('.md') || entry.name.endsWith('.mdx')) &&
      !['authors.yml', 'tags.yml'].includes(entry.name)
    ) {
      files.push(full);
    }
  }
  return files;
}

// Extract YYYY-MM-DD from the folder/file name. Docusaurus blog posts are
// conventionally named with a leading date (matches its own behaviour).
function dateFromPath(filePath) {
  const folder = path.basename(path.dirname(filePath));
  const file = path.basename(filePath, path.extname(filePath));
  const candidate = folder === 'blog' ? file : folder;
  const match = candidate.match(/^(\d{4})-(\d{2})-(\d{2})/);
  if (match) return `${match[1]}-${match[2]}-${match[3]}`;
  return null;
}

function slugFromFrontmatter(fm, filePath) {
  if (typeof fm.slug === 'string' && fm.slug.length > 0) return fm.slug;
  // Fall back to the folder name minus the date prefix.
  const folder = path.basename(path.dirname(filePath));
  const name = folder === 'blog' ? path.basename(filePath, path.extname(filePath)) : folder;
  return name.replace(/^\d{4}-\d{2}-\d{2}-/, '');
}

function authorsFromFrontmatter(fmAuthors, registry) {
  if (!fmAuthors) return [];
  const list = Array.isArray(fmAuthors) ? fmAuthors : [fmAuthors];
  return list
    .map((entry) => {
      if (typeof entry === 'string') {
        const a = registry[entry];
        if (!a) return {key: entry, name: entry};
        return {key: entry, name: a.name, imageURL: a.image_url, title: a.title};
      }
      if (entry && typeof entry === 'object' && entry.name) {
        return {key: entry.key || entry.name, name: entry.name, imageURL: entry.image_url, title: entry.title};
      }
      return null;
    })
    .filter(Boolean);
}

function build() {
  const authors = readAuthors();
  const files = listPostFiles();
  const posts = files
    .map((filePath) => {
      const raw = fs.readFileSync(filePath, 'utf8');
      const {data: fm} = matter(raw);
      const date = (typeof fm.date === 'string' && fm.date) || dateFromPath(filePath);
      if (!date || !fm.title) return null;
      const slug = slugFromFrontmatter(fm, filePath);
      return {
        slug,
        permalink: `/blog/${slug.replace(/^\//, '')}/`,
        title: String(fm.title),
        description: typeof fm.description === 'string' ? fm.description : null,
        image: typeof fm.image === 'string' ? fm.image : null,
        date,
        authors: authorsFromFrontmatter(fm.authors, authors),
      };
    })
    .filter(Boolean)
    .sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : 0))
    .slice(0, MAX_POSTS);

  const banner = '// AUTO-GENERATED by scripts/generate-blog-index.js — do not edit by hand.\n';
  const types = `
export type BlogIndexAuthor = {
  key: string;
  name: string;
  title?: string | null;
  imageURL?: string | null;
};

export type BlogIndexEntry = {
  slug: string;
  permalink: string;
  title: string;
  description: string | null;
  image: string | null;
  date: string;
  authors: BlogIndexAuthor[];
};
`;
  const body = `\nexport const BLOG_INDEX: BlogIndexEntry[] = ${JSON.stringify(posts, null, 2)};\n`;
  fs.writeFileSync(OUTPUT_FILE, banner + types + body);
  console.log(`[generate-blog-index] wrote ${posts.length} post(s) to ${path.relative(process.cwd(), OUTPUT_FILE)}`);
}

build();
